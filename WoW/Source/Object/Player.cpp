uint32_t CGPlayer::DescriptorToMirrorOffset(uint32_t offset, uint32_t size, int32_t local, uint32_t base) {
    int32_t total = CGUnit::TotalFieldsSaved();

    return (offset & 3) + 4 * (total + CGPlayer::GetSavedIndexFromDataIndex((offset - base) >> 2, (size + 3) >> 2, local));
}

// VERIFY: f6210798 auto
// OFFSET: 0x004F5550
uint32_t CGPlayer::GetSavedIndexFromDataIndex(uint32_t index, uint32_t count, int32_t local) {
    for (uint32_t i = 0; i < sizeof(CGPlayer::s_mirrorFields) / sizeof(CGPlayer::s_mirrorFields[0]); i++) {
        if (CGPlayer::s_mirrorFields[i] == index) {
            return i;
        }
    }

    if (local) {
        for (uint32_t i = 0; i < sizeof(CGPlayer::s_localMirrorFields) / sizeof(CGPlayer::s_localMirrorFields[0]); i++) {
            if (CGPlayer::s_localMirrorFields[i] == index) {
                return i + sizeof(CGPlayer::s_mirrorFields) / sizeof(CGPlayer::s_mirrorFields[0]);
            }
        }
    }

    return CGPlayer::MIRROR_INDEX_NOT_FOUND;
}

// VERIFY: 25fe9486 manual
// OFFSET: 0x004F7290
float CGPlayer::GetDrunknessTurnValue() {
    int32_t drunk = this->m_player->inebriation;
    int32_t fakeDrunk = this->m_player->m_playerFakeInebriation;
    int32_t value = drunk > fakeDrunk ? drunk : fakeDrunk;

    if (value >= 100) {
        value = 100;
    }

    return static_cast<uint8_t>(value) * 0.01f;
}

// VERIFY: ce82abd2 manual
// OFFSET: 0x00546100
int32_t CGPlayer::HasZoneExplored(int32_t zone) {
    if (static_cast<uint32_t>(zone / 8) >= sizeof(this->m_player->m_playerExploredZones1)) {
        return 1;
    }

    return this->m_player->m_playerExploredZones1[zone / 8] & (1 << (zone % 8));
}

